    public boolean insert(Material material) {
        String sql = """
            INSERT INTO materials (
                name, category, unit, quantity, price_per_unit, threshold,
                is_active, expiry_date, description, supplier,
                created_at, updated_at, created_by, updated_by
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """;

        try (PreparedStatement stmt = prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            stmt.setString(1, material.getName());
            stmt.setString(2, material.getCategory());
            stmt.setString(3, material.getUnit());
            stmt.setBigDecimal(4, material.getQuantity());
            stmt.setBigDecimal(5, material.getPricePerUnit());
            stmt.setBigDecimal(6, material.getThreshold());
            stmt.setBoolean(7, material.isActive());

            if (material.getExpiryDate() != null) {
                stmt.setDate(8, Date.valueOf(material.getExpiryDate()));
            } else {
                stmt.setNull(8, Types.DATE);
            }

            stmt.setString(9, material.getDescription());

            if (material.getSupplier() != null) {
                stmt.setString(10, material.getSupplier());
            } else {
                stmt.setNull(10, Types.VARCHAR);
            }

            stmt.setTimestamp(11, Timestamp.valueOf(material.getCreatedAt()));
            stmt.setTimestamp(12, Timestamp.valueOf(material.getUpdatedAt()));
            stmt.setInt(13, material.getCreatedBy());
            stmt.setInt(14, material.getUpdatedBy());

            int result = stmt.executeUpdate();
            if (result > 0) {
                ResultSet keys = stmt.getGeneratedKeys();
                if (keys.next()) {
                    material.setId(keys.getInt(1));
                }
                return true;
            }
        } catch (SQLException e) {
            System.err.println("Error inserting material: " + e.getMessage());
            e.printStackTrace();
        }
        return false;
    }

