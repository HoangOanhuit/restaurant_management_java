    private String resolveTableName() {
        try {
            DatabaseMetaData meta = conn.getMetaData();
            ResultSet rs = meta.getTables(null, null, "materials", null);
            if (rs.next()) {
                return "materials";
            }
            rs = meta.getTables(null, null, "active_materials", null);
            if (rs.next()) {
                return "active_materials";
            }
        } catch (SQLException e) {
            System.err.println("Error detecting materials table: " + e.getMessage());
        }
        return "materials";
    }

    private String withTableName(String sql) {
        return sql.replace("materials", tableName);
    }

    private PreparedStatement prepareStatement(String sql) throws SQLException {
        return conn.prepareStatement(withTableName(sql));
    }

    private PreparedStatement prepareStatement(String sql, int autoGeneratedKeys) throws SQLException {
        return conn.prepareStatement(withTableName(sql), autoGeneratedKeys);
    }

