    /**
     * Lấy thống kê tồn kho theo category
     */
    public Map<String, Map<String, Object>> getInventoryStatsByCategory() {
        Map<String, Map<String, Object>> stats = new HashMap<>();
        String sql = """
            SELECT 
                category,
                COUNT(*) as material_count,
                SUM(quantity * price_per_unit) as total_value,
                SUM(CASE WHEN quantity <= threshold THEN 1 ELSE 0 END) as low_stock_count,
                SUM(CASE WHEN quantity <= 0 THEN 1 ELSE 0 END) as out_of_stock_count
            FROM materials 
            WHERE is_active = 1 
            GROUP BY category
            ORDER BY total_value DESC
            """;

        try (PreparedStatement stmt = prepareStatement(sql);
             ResultSet rs = stmt.executeQuery()) {

            while (rs.next()) {
                String category = rs.getString("category");
                if (category == null) category = "Không phân loại";

                Map<String, Object> categoryStat = new HashMap<>();
                categoryStat.put("material_count", rs.getInt("material_count"));
                categoryStat.put("total_value", rs.getBigDecimal("total_value"));
                categoryStat.put("low_stock_count", rs.getInt("low_stock_count"));
                categoryStat.put("out_of_stock_count", rs.getInt("out_of_stock_count"));

                stats.put(category, categoryStat);
            }
        } catch (SQLException e) {
            System.err.println("Error getting inventory stats by category: " + e.getMessage());
            e.printStackTrace();
        }
        return stats;
    }

