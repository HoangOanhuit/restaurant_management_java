    private Material mapResultSet(ResultSet rs) throws SQLException {
        Material material = new Material();

        ResultSetMetaData meta = rs.getMetaData();
        int columnCount = meta.getColumnCount();
        java.util.Set<String> columns = new java.util.HashSet<>();
        for (int i = 1; i <= columnCount; i++) {
            columns.add(meta.getColumnLabel(i).toLowerCase());
        }

        if (columns.contains("id")) material.setId(rs.getInt("id"));
        if (columns.contains("name")) material.setName(rs.getString("name"));
        if (columns.contains("category")) material.setCategory(rs.getString("category"));
        if (columns.contains("unit")) material.setUnit(rs.getString("unit"));
        if (columns.contains("quantity")) material.setQuantity(rs.getBigDecimal("quantity"));
        if (columns.contains("price_per_unit")) material.setPricePerUnit(rs.getBigDecimal("price_per_unit"));
        if (columns.contains("threshold")) material.setThreshold(rs.getBigDecimal("threshold"));
        if (columns.contains("is_active")) material.setActive(rs.getBoolean("is_active"));
        if (columns.contains("description")) material.setDescription(rs.getString("description"));
        if (columns.contains("supplier")) material.setSupplier(rs.getString("supplier"));
        if (columns.contains("created_by")) material.setCreatedBy(rs.getInt("created_by"));
        if (columns.contains("updated_by")) material.setUpdatedBy(rs.getInt("updated_by"));

        if (columns.contains("expiry_date")) {
            Date expiryDate = rs.getDate("expiry_date");
            if (expiryDate != null) {
                material.setExpiryDate(expiryDate.toLocalDate());
            }
        }

        if (columns.contains("created_at")) {
            Timestamp createdAt = rs.getTimestamp("created_at");
            if (createdAt != null) {
                material.setCreatedAt(createdAt.toLocalDateTime());
            }
        }

        if (columns.contains("updated_at")) {
            Timestamp updatedAt = rs.getTimestamp("updated_at");
            if (updatedAt != null) {
                material.setUpdatedAt(updatedAt.toLocalDateTime());
            }
        }

        return material;
    }


