    /**
     * Tìm kiếm nguyên liệu theo nhiều tiêu chí
     */
    public List<Material> searchMaterials(String keyword, String category, Boolean isActive) {
        List<Material> materials = new ArrayList<>();
        StringBuilder sql = new StringBuilder("""
            SELECT * FROM materials 
            WHERE 1=1
            """);
        List<Object> params = new ArrayList<>();

        if (keyword != null && !keyword.trim().isEmpty()) {
            sql.append(" AND (name LIKE ? OR description LIKE ?)");
            String searchPattern = "%" + keyword + "%";
            params.add(searchPattern);
            params.add(searchPattern);
        }

        if (category != null && !category.trim().isEmpty()) {
            sql.append(" AND category = ?");
            params.add(category);
        }

        if (isActive != null) {
            sql.append(" AND is_active = ?");
            params.add(isActive);
        }

        sql.append(" ORDER BY name");

        try (PreparedStatement stmt = prepareStatement(sql.toString())) {
            for (int i = 0; i < params.size(); i++) {
                stmt.setObject(i + 1, params.get(i));
            }

            ResultSet rs = stmt.executeQuery();
            while (rs.next()) {
                materials.add(mapResultSet(rs));
            }
        } catch (SQLException e) {
            System.err.println("Error searching materials: " + e.getMessage());
            e.printStackTrace();
        }
        return materials;
    }

